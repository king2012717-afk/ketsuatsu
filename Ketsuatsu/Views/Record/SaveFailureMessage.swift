import Foundation

/// 記録を端末に保存できなかったときに出す文面。
///
/// 保存に失敗しても、記録はアプリを開いている間は履歴に表示される（あとで自動的に保存されることもある）。
/// ただしアプリを終了すると消えることがあるので、そのことと、まず確かめること（空き容量）を伝える。
enum SaveFailureMessage {
    static let single = "この記録は履歴に表示されますが、アプリを終了すると消えることがあります。iPhone の空き容量を確認してください。"

    static func batch(unsavedCount: Int) -> String {
        "\(unsavedCount) 件を端末に保存できませんでした。これらの記録は履歴に表示されますが、アプリを終了すると消えることがあります。iPhone の空き容量を確認してください。"
    }
}
